import { readFile, writeFile } from 'node:fs/promises';
const url = new URL('../dist/data.json', import.meta.url);
const data = JSON.parse(await readFile(url, 'utf8'));
const bank = JSON.parse(await readFile(new URL('../dist/repertory.json', import.meta.url), 'utf8'));
const focused = JSON.parse(await readFile(new URL('../dist/focused-repertory.json', import.meta.url), 'utf8'));
data.version = focused.version;
data.expansion.activeQuestions = focused.questions.length;
data.expansion.minimumAnswersPerQuestion = bank.minimumAnswers;
data.expansion.reviewed = bank.checked;
data.expansion.coverageRevision = bank.coverageRevision;
data.expansion.currentDictionarySpellings = data.expansion.uniqueNormalizedSpellings + (bank.questions.find(q => q.dictionary)?.additions?.length || 0);
data.expansion.questionCountsByPack = Object.fromEntries([...new Set(focused.questions.map(q => q.pack))].map(pack => [pack, focused.questions.filter(q => q.pack === pack).length]));
data.expansion.currentEvidenceFile = 'focused-repertory.json';
data.expansion.rankingPolicy = 'Recent Spain data where available; explicitly labelled editorial estimates otherwise. Historical recognition is not a 2026 measurement.';
await writeFile(url, JSON.stringify(data));
console.log(`Repertory ${focused.version}: ${focused.questions.length} questions, minimum ${bank.minimumAnswers} canonical answers; ${focused.actorCount} actors.`);
